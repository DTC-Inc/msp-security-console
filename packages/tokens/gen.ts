// The DTC tokens for the web app, generated from the DTC design system's canonical console block
// (design/console-tokens.css), never copied by hand: run `bun run tokens --from=<path to console-tokens.css>` (or set
// TOKENS_CSS) to regenerate tokens.json, and `bun run tokens:check` the same way to fail on drift. Each scheme's values are resolved here,
// and the web app turns them into its own CSS custom properties (web/src/tokens-css.ts). The console's own roles (severity, sources, trust) are x-roles.json.
import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve } from "path";

const args = process.argv.slice(2);
const from = args.find((a) => a.startsWith("--from="))?.slice(7)
  ?? process.env.TOKENS_CSS
  ?? resolve(import.meta.dir, "design/console-tokens.css");
const out = resolve(import.meta.dir, "tokens.json");

export function parse(css: string) {
  const decls = (body: string) => Object.fromEntries([...body.matchAll(/--dtc-([\w-]+):\s*([^;]+);/g)].map((m) => [m[1], m[2].trim()]));
  const darkAt = css.indexOf("@media (prefers-color-scheme: dark)");
  const light = decls(css.slice(css.indexOf(":root"), darkAt < 0 ? undefined : darkAt));
  const dark = { ...light, ...(darkAt < 0 ? {} : decls(css.slice(darkAt))) };
  // Resolve var(--dtc-x) references within a scheme.
  const res = (s: Record<string, string>) => Object.fromEntries(Object.entries(s).map(([k, v]) => [k, v.replace(/var\(--dtc-([\w-]+)\)/g, (_m, n) => s[n] ?? _m)]));
  return { light: res(light), dark: res(dark) };
}

if (import.meta.main) {
  if (!existsSync(from)) { console.error(`no DTC console tokens at ${from}: pass --from=<path to console-tokens.css> or set TOKENS_CSS`); process.exit(2); }
  const t = { _source: "the DTC design system's design/console-tokens.css (generated by packages/tokens/gen.ts; do not edit)", ...parse(readFileSync(from, "utf8")) };
  const text = JSON.stringify(t, null, 2) + "\n";
  if (args.includes("--check")) {
    const have = existsSync(out) ? readFileSync(out, "utf8") : "";
    if (have !== text) { console.error("packages/tokens/tokens.json differs from the DTC design system: run `bun run tokens`"); process.exit(1); }
    console.log("tokens match the DTC design system");
  } else { writeFileSync(out, text); console.log(`wrote ${out}`); }
}
