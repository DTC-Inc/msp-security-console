// The client's contract types, generated from contract.schema.json, which the server writes from its Rust types
// (server/src/contract.rs, `cargo run --bin contract-schema`): one source of truth. `bun run contract` regenerates
// both; `bun run contract:check` fails if src/index.ts no longer matches the schema.
import { readFileSync, writeFileSync, existsSync } from "fs";
import { resolve } from "path";

const schema = JSON.parse(readFileSync(resolve(import.meta.dir, "contract.schema.json"), "utf8"));
const defs: Record<string, any> = schema.$defs ?? {};
const out = resolve(import.meta.dir, "src/index.ts");

function ts(s: any): string {
  if (s.$ref) return s.$ref.split("/").pop();
  if (s.anyOf) return s.anyOf.filter((x: any) => x.type !== "null").map(ts).join(" | ");
  if (s.enum) return s.enum.map((v: string) => JSON.stringify(v)).join(" | ");
  const types = (Array.isArray(s.type) ? s.type : [s.type]).filter((t: string) => t !== "null");
  return types.map((t: string) => t === "integer" || t === "number" ? "number" : t === "array" ? `${ts(s.items)}[]` : t).join(" | ");
}
const nullable = (s: any) => (Array.isArray(s.type) && s.type.includes("null")) || (s.anyOf ?? []).some((x: any) => x.type === "null") || s.default !== undefined;

export function generate(): string {
  const lines = ["// GENERATED by packages/contract/gen.ts from contract.schema.json (the server's Rust types). Do not edit: change", "// server/src/contract.rs and run `bun run contract`.", ""];
  lines.push(`export const READ_OPS = ${JSON.stringify(defs.ReadOp.enum)} as const;`);
  lines.push("export type ReadOp = (typeof READ_OPS)[number];");
  for (const [name, d] of Object.entries(defs)) {
    if (name === "ReadOp") continue;
    if (d.enum) { lines.push(`export type ${name} = ${ts(d)};`); continue; }
    lines.push(`export type ${name} = {`);
    for (const [k, p] of Object.entries<any>(d.properties ?? {})) lines.push(`  ${k}${nullable(p) || !(d.required ?? []).includes(k) ? "?" : ""}: ${ts(p)};`);
    lines.push("};");
  }
  lines.push("export type EvidenceRequest = {");
  for (const [k, p] of Object.entries<any>(schema.properties)) lines.push(`  ${k}${(schema.required ?? []).includes(k) ? "" : "?"}: ${ts(p)};`);
  lines.push("};");
  lines.push("", "// The evidence API's answer (contract v1), passed through unchanged by the server.",
    "export type Answer<T = any> = {", "  v: 1; op: string; data?: T; next_cursor?: string | null; totals?: Record<string, number>; as_of?: Record<string, string | null>;",
    "  error?: string; refused?: boolean;",
    "  /** A feature that's off in this console, and why (cve.similar without its embedder). */", "  off?: string;",
    "  /** Why an answer that's on has no rows (cve.similar for a CVE not embedded yet). */", "  note?: string;",
    "  /** The model the answer's vectors came from (cve.similar). */", "  model?: string;", "};", "");
  return lines.join("\n");
}

if (import.meta.main) {
  const text = generate();
  if (process.argv.includes("--check")) {
    if (!existsSync(out) || readFileSync(out, "utf8") !== text) { console.error("packages/contract/src/index.ts doesn't match the schema: run `bun run contract`"); process.exit(1); }
    console.log("contract types match the schema");
  } else { writeFileSync(out, text); console.log(`wrote ${out}`); }
}
